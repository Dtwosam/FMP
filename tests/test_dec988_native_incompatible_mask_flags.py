from __future__ import annotations

import errno
import importlib.util
import os
from pathlib import Path
import sys
import tempfile
import unittest

SCRIPT = Path(__file__).resolve().parents[1] / "scripts/dec677_disposable_inotify_events.py"
spec = importlib.util.spec_from_file_location("dec677_native_dec988", SCRIPT)
module = importlib.util.module_from_spec(spec)
spec.loader.exec_module(module)

# Linux inotify registration options, NOT kernel event-record masks.
IN_MASK_CREATE = 0x10000000
IN_MASK_ADD = 0x20000000


@unittest.skipUnless(sys.platform == "linux", "native inotify flags require Linux")
class NativeIncompatibleWatchFlagsRegression(unittest.TestCase):
    def test_real_add_and_create_together_rejected_preserving_both_watches(self):
        fd = None
        with tempfile.TemporaryDirectory(
            prefix="dec988-public-incompatible-watch-flags-", dir="/tmp"
        ) as tmp:
            sample = Path(tmp) / "sample"
            self.assertEqual(sample.write_bytes(module.BEFORE), len(module.BEFORE))
            source_initial = os.lstat(sample)
            parent_initial = os.lstat(sample.parent)
            self.assertEqual(module._bounded_inventory_names(sample.parent),
                             ("sample",))
            try:
                fd, source_wd, parent_wd = module._start_watch(sample)
                self.assertNotEqual(source_wd, parent_wd)
                self.assertEqual(module._read_receipt_pending(fd), b"")

                lib = module.ctypes.CDLL(None, use_errno=True)
                lib.inotify_add_watch.argtypes = [
                    module.ctypes.c_int, module.ctypes.c_char_p,
                    module.ctypes.c_uint32,
                ]
                lib.inotify_add_watch.restype = module.ctypes.c_int

                # The two mode bits are mutually exclusive even when an
                # existing source or parent subscription is present.
                # A failure MUST NOT be interpreted as watch removal.
                for candidate, other_flags in (
                    (sample, module.IN_DONT_FOLLOW),
                    (sample.parent, module.IN_DONT_FOLLOW | module.IN_ONLYDIR),
                ):
                    module.ctypes.set_errno(0)
                    got = lib.inotify_add_watch(
                        fd, module._checked_watch_path_bytes(candidate),
                        IN_MASK_CREATE | IN_MASK_ADD | module.IN_ATTRIB |
                        other_flags,
                    )
                    self.assertEqual(got, -1)
                    self.assertEqual(module.ctypes.get_errno(), errno.EINVAL)
                    self.assertEqual(module._read_receipt_pending(fd), b"")

                # The parent's CREATE/DELETE registrations still observe
                # real named public child mutations after both failures.
                sibling = sample.parent / "public-incompatible-flags-sibling"
                self.assertEqual(sibling.write_bytes(b"PUBLIC-SIBLING"),
                                 len(b"PUBLIC-SIBLING"))
                created = module._read_receipt_pending(fd)
                self.assertTrue(created)
                created_events = module._classify_stream(
                    created, source_wd, parent_wd
                )
                self.assertTrue(created_events["well_formed"])
                self.assertGreaterEqual(created_events["directory_changes"], 1)
                offset = 0
                names = []
                while offset < len(created):
                    wd, mask, cookie, n = module.EVENT.unpack_from(created, offset)
                    offset += module.EVENT.size
                    name = created[offset:offset + n].split(b"\0", 1)[0]
                    offset += n
                    self.assertEqual(cookie, 0)
                    names.append((wd, mask, name))
                self.assertEqual(offset, len(created))
                self.assertIn(
                    (parent_wd, module.IN_CREATE,
                     b"public-incompatible-flags-sibling"), names
                )
                os.unlink(sibling)
                deleted = module._read_receipt_pending(fd)
                self.assertTrue(deleted)
                deleted_events = module._classify_stream(
                    deleted, source_wd, parent_wd
                )
                self.assertTrue(deleted_events["well_formed"])
                self.assertGreaterEqual(deleted_events["directory_changes"], 1)
                self.assertEqual(module._read_receipt_pending(fd), b"")

                # Original source and named parent MODIFY subscriptions
                # survive; only public generated bytes are modified.
                for content in (module.AFTER, module.BEFORE):
                    with sample.open("r+b") as writer:
                        self.assertEqual(writer.write(content), len(content))
                        writer.truncate()
                        writer.flush()
                        os.fsync(writer.fileno())
                    stream = module._read_receipt_pending(fd)
                    self.assertTrue(stream)
                    parsed = module._classify_stream(
                        stream, source_wd, parent_wd
                    )
                    self.assertTrue(parsed["well_formed"])
                    self.assertFalse(parsed["invalidated"])
                    self.assertGreaterEqual(parsed["source_modify_events"], 1)
                    self.assertGreaterEqual(
                        parsed["source_content_write_events"], 1
                    )
                    offset = 0
                    named_modification = False
                    while offset < len(stream):
                        wd, mask, cookie, n = module.EVENT.unpack_from(
                            stream, offset
                        )
                        offset += module.EVENT.size
                        name = stream[offset:offset + n].split(b"\0", 1)[0]
                        offset += n
                        if (wd == parent_wd and mask & module.IN_MODIFY
                                and name == b"sample"):
                            named_modification = True
                    self.assertEqual(offset, len(stream))
                    self.assertTrue(named_modification)
                    self.assertEqual(module._read_receipt_pending(fd), b"")

                    verdict = module._evaluate(
                        module.BEFORE, content, stream, source_wd,
                        True, False, directory_watch=parent_wd,
                        directory_inventory_names=("sample",),
                    )
                    self.assertEqual(verdict["status"], "BLOCKED")
                    self.assertIs(verdict["can_authorize_dispatch"], False)
                    self.assertIs(verdict["independent_os_proof_verified"], False)

                self.assertEqual(sample.read_bytes(), module.BEFORE)
                final = os.lstat(sample)
                parent_final = os.lstat(sample.parent)
                self.assertEqual(
                    (final.st_dev, final.st_ino, final.st_mode),
                    (source_initial.st_dev, source_initial.st_ino,
                     source_initial.st_mode),
                )
                self.assertEqual(
                    (parent_final.st_dev, parent_final.st_ino,
                     parent_final.st_mode),
                    (parent_initial.st_dev, parent_initial.st_ino,
                     parent_initial.st_mode),
                )
                self.assertEqual(module._bounded_inventory_names(sample.parent),
                                 ("sample",))
            finally:
                if fd is not None:
                    os.close(fd)
                    with self.assertRaises(OSError):
                        os.fstat(fd)
